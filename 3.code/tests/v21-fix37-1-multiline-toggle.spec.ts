import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'http://localhost:5173';
const ROWS = '#content .text[contenteditable="true"]';
const TXT = (i: number) => '第' + (i + 1) + '行 FIX37 跨行格式 ABCDEFGHIJ';
const BOLD = /<(b|strong)\b|font-weight\s*:\s*(bold|bolder|[6-9]\d\d)/i;
test('fix37-1 · 跨行加粗再次点击整体取消（标签移除 + 文本零丢失）', async ({ browser }) => {
  const ctx = await browser.newContext({ baseURL: BASE, viewport: { width: 1280, height: 900 } });
  await ctx.route(BASE + '/**', (r) => { const p = new URL(r.request().url()).pathname; const f = path.join(ROOT, 'dist', p === '/' ? 'index.html' : decodeURIComponent(p)); try { return r.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: fs.readFileSync(f) }); } catch { throw new Error('dist/index.html 缺失，请先 vite build'); } });
  const page = await ctx.newPage();
  await page.goto(BASE, { waitUntil: 'load' });
  await page.waitForFunction(() => { const J = (window as any).JU; return !!(J && J.actions && J.actions.addNode); }, null, { timeout: 60_000 });
  await page.evaluate((t: string[]) => { const J: any = (window as any).JU; const st = J.getState(); const d = (st.ui && st.ui.currentDocId) || st.rootId; ['sidebarRight', 'sidebarLeft'].forEach((id) => { const e = document.getElementById(id); if (e) e.classList.remove('collapsed'); }); t.forEach((x) => J.actions.addNode(d, null, { text: x })); if (typeof J.forceRender === 'function') J.forceRender(); }, [0, 1, 2].map(TXT));
  await page.waitForTimeout(400);
  const g = await page.evaluate((sel) => { const r = Array.from(document.querySelectorAll(sel)) as HTMLElement[]; const a = r[0].getBoundingClientRect(), b = r[2].getBoundingClientRect(); return { x1: a.left + 4, y1: a.top + a.height / 2, x2: b.left + Math.min(200, b.width - 4), y2: b.top + b.height / 2 }; }, ROWS);
  await page.mouse.move(g.x1, g.y1); await page.mouse.down(); await page.mouse.move(g.x2, g.y2, { steps: 20 }); await page.mouse.up();
  await page.waitForTimeout(300);
  expect(await page.evaluate(() => ((window as any).__juXsel.describe() || {}).covered), '拖选必须覆盖 ≥2 块').toBeGreaterThanOrEqual(2);
  const read = () => page.evaluate((sel) => (Array.from(document.querySelectorAll(sel)) as HTMLElement[]).map((e) => ({ html: e.innerHTML, text: (e.textContent || '').trim() })), ROWS);
  const bold = page.locator('#sidebarRight [data-cmd="bold"], [data-cmd="bold"]').first();
  await bold.click();
  await page.waitForTimeout(500);
  const on = await read();
  expect(on.filter((x) => BOLD.test(x.html)).length, '跨行加粗必须覆盖全部被选中的块').toBeGreaterThanOrEqual(2);
  await bold.click();
  await page.waitForTimeout(500);
  const off = await read();
  expect(off.filter((x) => BOLD.test(x.html)).length, '再次点击后不得残留任何加粗标签 / 声明').toBe(0);
  expect(off.map((x) => x.text), '取消格式后文本零丢失').toEqual(on.map((x) => x.text));
  await ctx.close();
});
